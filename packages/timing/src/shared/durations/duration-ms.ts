/** A duration that a caller may read as a number. */
type ReadableName = (typeof READABLE)[number];

/**
 * One duration, as a number for what takes one.
 * @param name Which one.
 * @returns It, in milliseconds.
 */
function durationMs(name: ReadableName): number {
	return durationOf(name);
}

export { durationMs };
export type { ReadableName };
