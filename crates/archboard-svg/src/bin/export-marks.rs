//! Print the marks a viewer draws beside a picture as TypeScript constants:
//! line widths, the arrowhead's length, each line's and pulse's ink, each
//! standing's pin and the warning, as the painter draws them in a picture.
//! `scripts/build-core.ts` writes them beside the WebAssembly build, so a pane
//! that draws a key, a pin or a warning holds no copy of the painter's rules.

use archboard_scene::js;
use archboard_scene::names::word;
use archboard_scene::paint::viewer_marks;
use archboard_scene::request::PaletteColor;
use archboard_scene::scene::Colour;
use archboard_svg::{colour, markup};

/// A string as a TypeScript literal.
fn quoted(text: &str) -> String {
    format!("\"{}\"", text.replace('\\', "\\\\").replace('"', "\\\""))
}

/// An object literal of some entries, each a key and a literal value.
fn object(entries: impl IntoIterator<Item = (&'static str, String)>) -> String {
    let fields: Vec<String> = entries
        .into_iter()
        .map(|(key, value)| format!("\t{key}: {value},"))
        .collect();
    format!("{{\n{}\n}} as const", fields.join("\n"))
}

/// Inks by the colour of their line, the neutral line's first.
fn inks(table: &[(Option<PaletteColor>, Colour)]) -> String {
    object(table.iter().map(|(color, ink)| {
        (
            color.map_or("neutral", |color| word(&color)),
            quoted(&colour(ink)),
        )
    }))
}

/// Print the constants under the header that says where they came from.
#[expect(
    clippy::print_stdout,
    reason = "the binary's output is the TypeScript it prints, which build-core.ts reads"
)]
fn main() {
    let marks = viewer_marks();
    let constants = [
        (
            "How wide a line of each weight is drawn.",
            "LINE_WIDTH",
            object(
                marks
                    .line_widths
                    .iter()
                    .map(|(weight, width)| (word(weight), js::number(*width))),
            ),
        ),
        (
            "How long an arrowhead is from its base to its tip, at every weight; it is as wide.",
            "HEAD_LENGTH",
            js::number(marks.head_length),
        ),
        (
            "How thick an open arrowhead's arms are, in the ten-unit square it is drawn in.",
            "OPEN_ARM",
            js::number(marks.open_arm),
        ),
        (
            "How thick a pulse's core is on a line of no emphasis.",
            "PULSE_BREADTH",
            js::number(marks.pulse_breadth),
        ),
        (
            "The ink a line of each colour is drawn in.",
            "LINE_INK",
            inks(&marks.line_inks),
        ),
        (
            "The ink of the body of a pulse on a line of each colour.",
            "PULSE_INK",
            inks(&marks.pulse_inks),
        ),
        (
            "The pin each standing wears, centred on the origin; none for unchanged.",
            "STANDING_MARK",
            object(
                marks
                    .pins
                    .iter()
                    .map(|(standing, items)| (word(standing), quoted(&markup(items)))),
            ),
        ),
        (
            "The warning's marks, centred on the origin.",
            "WARNING_GLYPH",
            quoted(&markup(&marks.warning)),
        ),
        (
            "How far in from a box's corner its pin and its warning stand.",
            "CORNER_INSET",
            js::number(marks.corner_inset),
        ),
    ];
    println!(
        "// Generated by crates/archboard-svg/src/bin/export-marks.rs from the core's painter.\n// `bun run build:core` writes it; do not edit it."
    );
    for (doc, name, value) in constants {
        println!("\n/** {doc} */\nexport const {name} = {value};");
    }
}
