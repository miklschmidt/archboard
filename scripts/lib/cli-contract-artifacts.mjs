import fs from "node:fs";
import { join } from "node:path";

export const CLI_CONTRACT_ARTIFACT_NAMES = [
	"cli-command-audit.md",
	"command-contract-proof.json",
	"command-contract-proof.md",
];

const cell = (value) =>
	(Array.isArray(value) ? value.join("; ") : String(value ?? ""))
		.replaceAll("|", "\\|")
		.replaceAll("\n", " ");

const format = (root, name, content) => {
	const formatted = Bun.spawnSync(
		["bunx", "oxfmt", "--stdin-filepath", join(root, "docs", "design", "generated", name)],
		{
			cwd: root,
			stdin: new TextEncoder().encode(content),
			stdout: "pipe",
			stderr: "pipe",
		},
	);
	if (formatted.exitCode !== 0) {
		throw new Error(`Could not format ${name}: ${formatted.stderr.toString()}`);
	}
	return formatted.stdout.toString();
};

export const renderCliContractArtifacts = async (root) => {
	const audit = JSON.parse(
		fs.readFileSync(join(root, "docs", "design", "cli-command-audit.json"), "utf8"),
	);
	const { cliContractRegistry } = await import(join(root, "src", "cli", "commands", "run.ts"));
	const { introspectContracts } = await import(
		join(root, "src", "cli", "command-contract", "introspection.ts")
	);
	const registry = cliContractRegistry();
	const proof = introspectContracts(registry);
	const routes = registry.map(
		({ name, parent, handlerOwner, parserOwner, bare, childDiscovery }) => {
			const route = { name, parent, handlerOwner, parserOwner };
			if (bare) route.bare = bare;
			if (childDiscovery) route.childDiscovery = childDiscovery;
			return route;
		},
	);

	const auditMarkdown = [
		"<!-- Generated from ../cli-command-audit.json. Do not edit this file. -->",
		"# CLI command audit",
		"",
		`Reviewed base: \`${audit.reviewedBase}\`.`,
		"",
		`The canonical JSON records ${audit.surface.commands} commands, ${audit.surface.subcommands} subcommands, and ${audit.surface.paths} public paths.`,
		"",
		"| Path | Parser | Output/result | Prerequisites and relationships | Semantics and ordering | Next fields | Workflow |",
		"| --- | --- | --- | --- | --- | --- | --- |",
		...audit.entries.map(
			(entry) =>
				`| \`${cell(entry.path)}\` | ${cell(entry.parserOwner)} | ${cell(entry.stdout)}. ${cell(entry.result)} | ${cell(entry.prerequisites)}. ${cell(entry.relationships)} | ${cell(entry.semantics)}. ${cell(entry.ordering)} | ${cell(entry.nextFields)} | ${cell(entry.workflow)} |`,
		),
		"",
		"## Workflow deletion test",
		"",
		...audit.workflows.flatMap((workflow) => [
			`### ${workflow.name}`,
			"",
			`Classification: ${workflow.classification}. Decision: ${workflow.decision}.`,
			"",
			workflow.evidence,
			"",
			`Commands: ${workflow.commands.map((command) => `\`${command}\``).join(", ")}. Follow-up: ${workflow.followUpTask ?? "none approved"}.`,
			"",
		]),
	].join("\n");

	const proofJson =
		JSON.stringify(
			{
				schemaVersion: 6,
				generatedFrom: "src/cli/commands/run.ts",
				routes,
				contracts: proof,
			},
			null,
			2,
		) + "\n";

	const proofMarkdown = [
		"<!-- Generated from the run.ts registry and public CommandContract metadata. -->",
		"# Command contract proof reference",
		"",
	];
	for (const contract of proof) {
		proofMarkdown.push(
			`## ${contract.path.join(" ")}`,
			"",
			contract.description,
			"",
			"Usage:",
			"",
			"```text",
			`archboard ${contract.usage}`,
			"```",
			"",
			`Output: ${contract.output.map((output) => `${output.mode} (${output.description})`).join("; ")}.`,
			"",
			`Prerequisites: ${contract.prerequisites.join(", ") || "none"}. Effects: ${contract.effects.join(", ") || "none"}.`,
			"",
			"REST relationships:",
			"",
			...contract.relationships.map(
				(relationship) =>
					`- ${relationship.method} \`${relationship.path}\`, ${relationship.cardinality}. ${relationship.description}`,
			),
			"",
			"Public result JSON Schema:",
			"",
			"```json",
			JSON.stringify(contract.result, null, 2),
			"```",
			"",
		);
	}

	const rawArtifacts = new Map([
		["cli-command-audit.md", auditMarkdown + "\n"],
		["command-contract-proof.json", proofJson],
		["command-contract-proof.md", proofMarkdown.join("\n") + "\n"],
	]);
	const artifacts = new Map(
		[...rawArtifacts].map(([name, content]) => [name, format(root, name, content)]),
	);
	return { artifacts, audit, proof, registry, routes };
};
